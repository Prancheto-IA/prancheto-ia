import * as React from 'react';
import { cva } from 'class-variance-authority';
import { cn } from '@/lib/utils';

const badgeVariants = cva(
  'inline-flex items-center rounded-full border px-2.5 py-0.5 text-xs font-semibold transition-colors focus:outline-none focus:ring-2 focus:ring-ring focus:ring-offset-2 select-none',
  {
    variants: {
      variant: {
        default: 'border-transparent bg-brand-primary text-white shadow-2xs',
        secondary: 'border-surface-border bg-surface-subtle text-ink-primary hover:bg-surface-hover',
        destructive: 'border-transparent bg-feedback-error text-white shadow-2xs',
        outline: 'border-surface-border text-ink-secondary bg-surface-card',
      },
    },
    defaultVariants: {
      variant: 'default',
    },
  }
);

function Badge({ className, variant, ...props }) {
  return (
    <div className={cn(badgeVariants({ variant }), className)} {...props} />
  );
}

export { Badge, badgeVariants };

